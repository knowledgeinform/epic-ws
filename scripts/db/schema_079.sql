DROP PROCEDURE IF EXISTS execute;
delimiter //
CREATE PROCEDURE execute()
BEGIN

    DECLARE db varchar(20);
    DECLARE majVersion INT;
    DECLARE minVersion INT;

    SELECT database() INTO db;
    SELECT major, minor FROM version WHERE type = 'DATABASE' INTO majVersion, minVersion;

    IF majVersion = 78 AND minVersion = 0
    THEN
        -- This was a schema change that was put into dev only (to support line edit refactor)
        -- leaving this db increment here as there are subsequent database version changes.
        -- Originally, this was changing the schema to support refactoring of line edits
        -- These changes have been reverted on dev branch as the changes were partial and did not work
        -- Need to wait until feature changes are in a better state before adding this back.

        -- -----------------------------------------------------
        -- Update version numbers
        -- -----------------------------------------------------
        SET majVersion = 79;
        SET minVersion = 0;
        UPDATE version
        SET major = majVersion,
            minor = minVersion
        WHERE type = 'DATABASE';

    END IF;

    -- DO NOT ADD ANYTHING AFTER THIS
END//
delimiter ;
CALL execute();
DROP PROCEDURE execute;
